// Generates tests/figma-audit.js (the paste-ready audit for the Figma MCP `use_figma` tool) from
// plugin-dev/src/auditCore.js, the same module the developer test runner uses, so they cannot drift.
//   node scripts/gen-figma-audit.mjs          write tests/figma-audit.js
//   node scripts/gen-figma-audit.mjs --check  exit 1 if tests/figma-audit.js is stale
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const CORE_PATH = path.join(rootDir, 'plugin-dev/src/auditCore.js')
export const OUT_PATH = path.join(rootDir, 'tests/figma-audit.js')

const HEADER = `// Mermapix Figma structure audit (Phase 8.6 / 10.2).
//
// GENERATED by scripts/gen-figma-audit.mjs from plugin-dev/src/auditCore.js - do not edit by hand
// (edit the module, then run \`pnpm build:test-runner\` or \`node scripts/gen-figma-audit.mjs\`).
//
// Paste-ready body for the Figma MCP \`use_figma\` tool (plain JS, no imports, top-level return).
// It audits every diagram on the CURRENT page: top-level FRAMEs (plugin inserts) and FRAMEs inside
// SECTIONs (Mermapix Test Runner pages). Read-only - it never mutates the file.
//
// Targets (Phase 8 goal):
//   duplicateStacks   0  - no two shapes stacked at the exact same bounds (double markers, fill+outline pairs)
//   looseShapes       0  - no fill/outline VECTOR outside a frame, except connectors/markers
//   unconvertedTables 0  - every ERD entity became an Auto Layout table
//   overflowingText   0  - no text wider than its Auto Layout cell
//   unnamedLayers     v  - generic "Vector"/"Group" names should trend to 0
// Added in 10.2 (need the test runner's per-diagram \`meta\` shared plugin data, else they are null / skipped):
//   contentOverflow   0  - no descendant outside the root frame's bounds (frame too small, content cropped)
//   textsLost         0  - TEXT nodes >= non-empty <text> elements of the payload SVG
//   blackBoxes        0  - near-black (light) / near-white (dark) shapes covering >25% of their parent
`

const FOOTER = `
return findDiagramRoots(figma.currentPage).map((n) => {
  const a = auditDiagram(n, readMeta(n))
  const s = summarizeAudit(a)
  a.ok = s.ok
  a.issues = s.issues
  return a
})
`

export function generate() {
  const core = fs
    .readFileSync(CORE_PATH, 'utf8')
    .replace(/^export (const|function) /gm, '$1 ')
    .replace(/^\/\/ Mermapix Figma structure audit[\s\S]*?\n\n/, '')
  if (/^export\s/m.test(core) || /^import\s/m.test(core)) throw new Error('auditCore.js must not use import/export syntax beyond export const/function')
  return HEADER + '\n' + core.trimEnd() + '\n' + FOOTER
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = generate()
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT_PATH) || fs.readFileSync(OUT_PATH, 'utf8') !== out) {
      console.error('tests/figma-audit.js is stale: run `node scripts/gen-figma-audit.mjs`')
      process.exit(1)
    }
  } else {
    fs.writeFileSync(OUT_PATH, out, 'utf8')
    console.log(`✅ Wrote ${path.relative(rootDir, OUT_PATH)}`)
  }
}
